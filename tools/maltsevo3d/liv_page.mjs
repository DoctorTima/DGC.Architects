import puppeteer from 'puppeteer-core';
const [,, out, w, h, mob] = process.argv;
const browser = await puppeteer.launch({ executablePath: '/usr/bin/google-chrome', headless: 'new', args: ['--no-sandbox', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--enable-webgl'] });
const page = await browser.newPage();
await page.setViewport({ width: +w, height: +h, deviceScaleFactor: 1, isMobile: !!mob, hasTouch: !!mob });
const logs = [];
page.on('console', (m) => logs.push(m.type() + ': ' + m.text()));
page.on('pageerror', (e) => logs.push('PAGEERROR: ' + e.message));
page.on('requestfailed', (r) => logs.push('REQFAIL: ' + r.url()));
page.on('response', (r) => { if (r.status() >= 400) logs.push('HTTP ' + r.status() + ' ' + r.url()); });
await page.goto('http://127.0.0.1:8731/maltsevo-3d/', { waitUntil: 'load', timeout: 120000 });
await new Promise((r) => setTimeout(r, 1200));
await page.screenshot({ path: out + '_1hero.png' });
await page.evaluate(() => document.getElementById('model').scrollIntoView());
await page.waitForFunction(() => document.querySelector('#viewer.is-live, #viewer.is-failed'), { timeout: 120000 }).catch(() => logs.push('WAIT TIMEOUT'));
await new Promise((r) => setTimeout(r, 2600));
await page.screenshot({ path: out + '_2model.png' });
await page.evaluate(() => window.scrollBy(0, 500));
await new Promise((r) => setTimeout(r, 600));
await page.screenshot({ path: out + '_3stops.png' });
await page.click('.stop[data-stop="living-1"]');
await new Promise((r) => setTimeout(r, 2600));
await page.screenshot({ path: out + '_4inside.png' });
await page.click('[data-kitchen="B"]');
await page.click('.stop[data-stop="kitchen-1"]');
await new Promise((r) => setTimeout(r, 2200));
await page.screenshot({ path: out + '_5k2.png' });
await page.click('[data-act="full"]');
await new Promise((r) => setTimeout(r, 1200));
await page.screenshot({ path: out + '_6full.png' });
console.log(logs.join('\n'));
await browser.close();
